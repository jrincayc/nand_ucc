#!/usr/bin/env python3
"""hd2asm.py -- MECHANICAL encoder  HD (hd/*.hd)  ->  commented data assembly (.byte/.word) for asm.py, plus an independent
decoder (image bytes -> flat node graph) used by the tests.  No design decisions are made here: every byte is a direct
transcription of a line of the HD file, and each emitted line quotes that HD line in its comment (Y_SPEC.md section 4).

ROM data layout (addresses relative to ROM_BASE; code occupies the part below HD_BASE):
  HD_BASE        ab                      1 byte  (address width; ROM address bits = ab-1)
  HD_DIR  (+0x20) directory              16 slots x 2 bytes: ROM address of the record of type t (slot t), 0 = empty
  HD_MODS (+0x40) module area            MOD_AREA bytes, records packed from the start (unused tail stays unprogrammed)
  HD_BODY (+0x240) body                  instances, END(0xFF); then chain record; then ports record
Module record: flags(0=primitive, 1=comb improvable, 2=tile) n_in n_out n_gates ; gates ; outs.  Every gate is (kind,a,b),
kind 0 nand 1 dff (a only; b=a).  Signals: 0..n_in-1 inputs, n_in+g = gate g.  Type 0 = primitive nand, type 1 = primitive dff
(records in slots 0 and 1), type 2+m = library module m.
Instance: type (0 nand, 1 dff, 2+m module m) then one ref per input.  Ref byte, relative to the first node of the instance
(the 'current' node):  0x01..0x7F backward distance;  0x80+j ROM data bit j;  0x88 tie-high node;  0x89 run;
0x8A+j RAM read bit j (output 8+j of the last tile);  0xFD lo hi backward distance;  0xFE lo hi forward distance.
Chain record: tile type, count, then one FIXED 5-byte rule per tile input in order (op, ref padded to 3 bytes, param):
0 BCAST ref | 1 PREV j | 2 PICKLO ref mask | 3 PICKHI ref divisor   (pick source = node(ref) + 2*idx nodes; idx = k&mask or k/divisor).
Refs in chain/ports are relative to current = n_core (the tie node).
Ports record: count, then per port: ref, sink pin x, sink pin y (bytes; coordinates relative to the issuing arm; the child arm is at (0,STRIDE)).
Order: rom_addr0.. arm_addr0..3 wdata0..7 arm_en (EN last so that its wire is the last before RUN)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE]
import hd as H, ref_flatten as RF

HD_OFF, DIR_OFF, MODS_OFF, BODY_OFF, MOD_AREA = 0x32E0, 0x3300, 0x3320, 0x34E0, 0x1C0
STRIDE, ARM_H = RF.STRIDE, RF.ARM_H
END = 0xFF


def prim(name):
    m = H.Module(name, 2 if name == 'nand' else 1, 1, 'prim')
    m.gates = [(0, 1)] if name == 'nand' else [('dff', 0)]
    m.outs = [m.n_in]; m.comments = ['the gate itself']
    m.gate_ins = lambda g, m=m: m.gates[g] if m.name == 'nand' else m.gates[g][1:]
    return m


class Enc:
    def __init__(self, hd, ab=None):
        self.hd = hd; self.f = RF.flatten(hd); self.ab = hd.params['ab']
        self.rom_base = 1 << (self.ab - 1)
        self.lines = []                      # (text, comment) ; text may be a directive or a label line
        self.base = {}                       # instance index -> first node

    def emit(self, text, comment): self.lines.append((text, comment))
    def byt(self, bs, comment): self.emit('.byte ' + ', '.join('0x%02X' % b for b in bs), comment)

    def ref(self, s, cur):
        f = self.f
        if s == 'run': return [0x89]
        if s == 'tie': return [0x88]
        if s.startswith('rom') and s[3:].isdigit(): return [0x80 + int(s[3:])]
        if s.startswith('ramrd') and s[5:].isdigit(): return [0x8A + int(s[5:])]
        kind, t = f.resolve(s)
        assert kind == 'n'
        if t == f.tie: return [0x88]
        if t < cur:
            d = cur - t
            return [d] if d <= 127 else [0xFD, d & 255, d >> 8]
        d = t - cur; assert d > 0
        return [0xFE, d & 255, d >> 8]

    def encode(self):
        hd, f = self.hd, self.f
        E = self.emit
        E('', f'hd_data.asm -- GENERATED by hd2asm.py from the HD file; do not edit by hand (edit the .hd and regenerate)')
        E('', 'layout and byte formats: see the header of hd2asm.py and Y_SPEC.md section 4')
        E(f'.equ HD_BASE, 0x{self.rom_base + HD_OFF:X}', 'start of the hardware description in ROM')
        E(f'.org HD_BASE', 'header')
        E('hd_header:', 'label: header')
        self.byt([self.ab], f'param ab = {self.ab} (address width; ROM has {self.ab - 1} address bits)')
        E(f'.org HD_BASE + 0x{DIR_OFF - HD_OFF:X}', 'record directory: 16 slots, slot t = record of type t')
        E('hd_dir:', 'label: directory')
        recs = [prim('nand'), prim('dff')] + list(hd.modules)
        for t in range(16):
            if t < len(recs): E(f'.word mod_{recs[t].name}', f'slot {t}: type {t} = {recs[t].name}')
            else: E('.word 0', f'slot {t}: empty')
        E(f'.org HD_BASE + 0x{MODS_OFF - HD_OFF:X}', f'record area ({MOD_AREA} bytes; records are packed; a child with smaller modules leaves the tail unused)')
        used = 0
        E('hd_mods:', 'label: start of the record area (the builder programs it type by type)')
        for m in recs:
            E(f'.org hd_mods + {used}', f'record {m.name} starts at a FIXED offset: records have the extent 4 + 3 slots + outputs, improved or not')
            E(f'mod_{m.name}:', f'label: record {m.name}')
            n = m.n_gates()
            fl = {'prim': 0, 'comb': 1, 'tile': 2}[m.kind]
            self.byt([fl, m.n_in, m.n_out, n],
                     f'{m.name}: flags={["primitive", "comb/improvable", "tile"][fl]}, n_in={m.n_in}, n_out={m.n_out}, n_gates={n} slots (a skip entry covers several)')
            sig = lambda s: f'i{s}' if s < m.n_in else f'g{s - m.n_in}'
            g = 0; ent = 0
            while g < n:
                cm = m.comments[g] if g < len(m.comments) else ''
                if m.gates[g] is None:                       # a run of unplaced slots (improved module): one skip entry
                    k = 0
                    while g + k < n and m.gates[g + k] is None and k < 255: k += 1
                    self.byt([2, k, 0], f'g{g}..g{g + k - 1}: {k} unplaced slot(s) (skip entry: kind 2, count)')
                    g += k; ent += 1; continue
                a = m.gate_ins(g)
                if m.kind == 'tile' and m.gates[g][0] == 'dff' or m.kind == 'prim' and m.gates[g][0] == 'dff':
                    self.byt([1, a[0], a[0]], f'g{g} = dff {sig(a[0])}   {cm}')
                else: self.byt([0, a[0], a[1]], f'g{g} = nand {sig(a[0])} {sig(a[1])}   {cm}')
                g += 1; ent += 1
            self.byt(m.outs, f'outputs: ' + ' '.join(sig(o) for o in m.outs))
            used += 4 + 3 * n + m.n_out                      # the fixed extent (an improved record may be shorter)
        assert used <= MOD_AREA, f'module area overflow: {used}'
        E(f'.org hd_mods + {used}', 'end of the records')
        E('hd_mods_end:', 'label: end of the record area')
        E(f'.org HD_BASE + 0x{BODY_OFF - HD_OFF:X}', 'body: instance list')
        E('hd_body:', 'label: body')
        typ = {'nand': 0, 'dff': 1}
        for i, m in enumerate(hd.modules): typ[m.name] = 2 + i
        node = 0
        for inst in hd.body:
            bs = [typ[inst.type]]
            for r in inst.refs: bs += self.ref(r, node)
            cm = f'{inst.name} = {inst.type} ' + ' '.join(inst.refs) + (f'   # {inst.comment}' if inst.comment else '')
            self.byt(bs, f'node {node}: ' + cm)
            node += 1 if inst.type in ('nand', 'dff') else hd.module(inst.type).n_gates()
        assert node == f.n_core
        self.byt([END], f'END of body; {node} core nodes; tie-high node = {node}')
        # chain
        ch = hd.chain; t = hd.module(ch['module']); cur = f.n_core
        E('hd_chain:', 'label: chain (RAM word tiles, one column per byte)')
        self.byt([typ[ch['module']], ch['count'] - 1], f'chain of {ch["count"]} x {ch["module"]} (type {typ[ch["module"]]}); the byte is the index of the last tile, count - 1')
        E('hd_rules:', 'label: tile input rules, 5 bytes each: op, ref (padded to 3 bytes), param')
        pad = lambda r: (r + [0, 0, 0])[:3]
        for i, kind, args in sorted(ch['rules']):
            if kind == 'bcast': self.byt([0] + pad(self.ref(args[0], cur)) + [0], f'tile input i{i}: BCAST {args[0]} (same source for every tile)')
            elif kind == 'prev': self.byt([1, 0, 0, 0, args[0]], f'tile input i{i}: PREV output {args[0]} of the previous tile (tile 0: tie-high)')
            elif kind == 'pick':
                lst = ch['lists'][args[0]]; nodes = [f.resolve(x)[1] for x in lst]
                assert all(nodes[q] == nodes[0] + 2 * q for q in range(len(nodes))), f'list {args[0]} is not stride 2'
                need = ((ch['count'] - 1) >> args[2]) + 1 if args[1] == 'hi' else min(args[2] + 1, ch['count'])
                assert len(lst) == need, f'list {args[0]} has {len(lst)} entries, needs {need}'
                par = args[2] if args[1] == 'lo' else 1 << args[2]
                assert args[1] == 'lo' or par <= 64, 'pickhi divisor must be at most 64'
                self.byt([2 if args[1] == 'lo' else 3] + pad(self.ref(lst[0], cur)) + [par],
                         f'tile input i{i}: PICK{args[1].upper()} list {args[0]} from {lst[0]}, stride 2 nodes, ' + (f'index = k AND {par}' if args[1] == 'lo' else f'index = k / {par}'))
        want = [(f'rom_addr{j}', 0, STRIDE + ARM_H + j) for j in range(self.ab - 1)] + [(f'arm_addr{j}', 0, STRIDE + j) for j in range(4)] + \
               [(f'wdata{j}', 1, STRIDE + j) for j in range(8)] + [('arm_en', 0, STRIDE + 4)]
        assert [n for n, _ in hd.ports] == [w[0] for w in want], 'ports not in the fixed order'
        E('hd_ports:', 'label: ports (ref, then the sink pin x, y relative to the issuing arm)')
        self.byt([len(hd.ports)], f'{len(hd.ports)} ports')
        for (n, r), (_, px, py) in zip(hd.ports, want): self.byt(self.ref(r, cur) + [px, py], f'port {n} = {r} -> pin ({px},{py})')
        return self

    def text(self):
        out = []
        for t, c in self.lines:
            if not t: out.append('// ' + c)
            elif t.endswith(':') and not t.startswith('.'): out.append(f'{t:<12}// {c}')
            else: out.append(f'    {t:<44}// {c}')
        return '\n'.join(out) + '\n'


# ------------------------------------------------------------------------------------------------ decoder (independent of the encoder)
class Dec:
    pass


def decode(image, ab):
    """image: bytes starting at ROM_BASE.  Returns an object shaped like ref_flatten.Flat (kind, ins, tkind, tins, ports, W, n_core ...)."""
    rb = 1 << (ab - 1)
    rd = lambda a: image[a - rb] if 0 <= a - rb < len(image) else 0
    hdb = rb + HD_OFF
    assert rd(hdb) == ab
    recs = []
    for s in range(16):
        a = rd(hdb + (DIR_OFF - HD_OFF) + 2 * s) | rd(hdb + (DIR_OFF - HD_OFF) + 2 * s + 1) << 8
        if not a: recs.append(None); continue
        fl, n_in, n_out, n = [rd(a + q) for q in range(4)]
        gs = []; q = a + 4
        while len(gs) < n:
            k, x, y = rd(q), rd(q + 1), rd(q + 2); q += 3
            if k == 2: gs += [None] * x
            else: gs.append((k, x, y))
        recs.append(dict(flags=fl, n_in=n_in, n_out=n_out, gates=gs, outs=[rd(q + j) for j in range(n_out)]))
    f = Dec(); f.kind, f.ins = [], []
    pos = hdb + (BODY_OFF - HD_OFF)
    def dref(p, cur):
        b = rd(p)
        if 1 <= b <= 0x7F: return ('n', cur - b), p + 1
        if 0x80 <= b <= 0x87: return ('rom', b - 0x80), p + 1
        if b == 0x88: return ('tie',), p + 1
        if b == 0x89: return ('run',), p + 1
        if 0x8A <= b <= 0x91: return ('ramrd', b - 0x8A), p + 1
        if b == 0xFD: return ('n', cur - (rd(p + 1) | rd(p + 2) << 8)), p + 3
        if b == 0xFE: return ('n', cur + (rd(p + 1) | rd(p + 2) << 8)), p + 3
        raise ValueError(f'bad ref byte {b:#x} at {p:#x}')
    while rd(pos) != END:
        ty = rd(pos); pos += 1; cur = len(f.kind); m = recs[ty]; src = []
        for _ in range(m['n_in']): s, pos = dref(pos, cur); src.append(s)
        for g, x in enumerate(m['gates']):
            if x is None: f.kind.append('hole'); f.ins.append(None); continue
            k, a, b = x
            f.kind.append('dff' if k else 'nand')
            f.ins.append([src[x] if x < m['n_in'] else ('n', cur + x - m['n_in']) for x in ((a,) if k else (a, b))])
    pos += 1
    f.n_core = len(f.kind); f.tie = f.n_core
    tty, W = rd(pos), rd(pos + 1) + 1; pos += 2; t = recs[tty]; f.W = W; f.TG = len(t['gates'])
    rules = {}
    for i in range(t['n_in']):
        op = rd(pos); r = None
        if op in (0, 2, 3): r, _ = dref(pos + 1, f.n_core)
        par = rd(pos + 4); pos += 5
        rules[i] = ('b', r) if op == 0 else ('p', par) if op == 1 else ('lo' if op == 2 else 'hi', r, par)
    f.n_nodes = f.n_core + 1 + W * f.TG
    tid = lambda k, j: f.n_core + 1 + k * f.TG + j
    def fix(r):
        if r[0] == 'tie': return ('n', f.tie)
        if r[0] == 'ramrd': return ('n', tid(W - 1, t['outs'][8 + r[1]] - t['n_in']))
        return r
    f.tkind, f.tins = [], []
    for k in range(W):
        def tin(s):
            r = rules[s]
            if r[0] == 'b': return fix(r[1])
            if r[0] == 'p': return ('n', f.tie) if k == 0 else ('n', tid(k - 1, t['outs'][r[1]] - t['n_in']))
            idx = (k & r[2]) if r[0] == 'lo' else (k // r[2])
            return ('n', fix(r[1])[1] + 2 * idx)
        for g, (kd, a, b) in enumerate(t['gates']):
            sg = lambda s: tin(s) if s < t['n_in'] else ('n', tid(k, s - t['n_in']))
            if kd: f.tkind.append('dff'); f.tins.append([sg(a)])
            else: f.tkind.append('nand'); f.tins.append([sg(a), sg(b)])
    np_ = rd(pos); pos += 1; f.ports = []; f.pins = []
    for _ in range(np_):
        r, pos = dref(pos, f.n_core); f.ports.append(r); f.pins.append((rd(pos), rd(pos + 1))); pos += 2
    f.end = pos
    def norm(r):
        if r[0] == 'tie': return ('n', f.tie)
        if r[0] == 'ramrd': return fix(r)
        return r
    f.ins = [None if x is None else [norm(s) for s in x] for x in f.ins]; f.ports = [norm(r) for r in f.ports]
    return f


