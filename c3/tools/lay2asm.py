#!/usr/bin/env python3
"""lay2asm.py LAY NL OUT.asm -- encode a layout as ROM data for the RV32EC builder.

Coordinates in the data are RELATIVE TO THE ARM's origin (the layout's ARM part position), so a copy is the same data shifted by CHILD_DX.
Stream (all in lay_data.asm, every byte on a commented line):
  kinds    2 bits per site, row-major, 4 per byte, first site in the low bits: 0 NAND, 1 DFF, 2 empty
  paths    one per sink, in this order: node pins (site order, pin A then B), then ports (nl order, EN last), then the RUN sinks.
           a path is a list of segments; segment byte  [7] last  [6] via  [5:4] dir (0 +x, 1 -x, 2 +y, 3 -y)  [3:0] length 1..15
           length field 0: the next byte is the length 1..255 (a next byte of 0 means: no path at all, the sink is skipped)
           the first segment's via bit means: start on layer 1; later via bits: VIA at the current end, then the layer toggles.
  tables   port start cells (x, y as 16-bit), RUN sink start cells (x, y)
"""
import sys, os
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__))]
import lay

DIRS = {(1, 0): 0, (-1, 0): 1, (0, 1): 2, (0, -1): 3}

def segments(pts):
    """-> list of (via, dir, length) from a point list [(x,y,l)...]; consecutive points on one layer are a straight segment, same x,y different layer is a via."""
    out = []; via = 1 if pts[0][2] == 1 else 0; cur = pts[0]
    assert pts[-1][2] == pts[-2][2] if len(pts) > 1 else True, 'path ends with a via'
    for b in pts[1:]:
        if b[2] != cur[2]: assert b[:2] == cur[:2]; via = 1; cur = b; continue
        dx, dy = b[0] - cur[0], b[1] - cur[1]; assert (dx == 0) != (dy == 0)
        n = abs(dx) + abs(dy); d = DIRS[((dx > 0) - (dx < 0), (dy > 0) - (dy < 0))]
        while n > 0:
            c = min(n, 255); out.append((via, d, c)); via = 0; n -= c
        cur = b
    return out

def enc_path(segs):
    """-> bytes"""
    if not segs: return bytes([0, 0])
    o = bytearray()
    for k, (v, d, n) in enumerate(segs):
        b = (0x80 if k == len(segs) - 1 else 0) | (0x40 if v else 0) | (d << 4)
        if n <= 15: o.append(b | n)
        else: o += bytes([b, n])
    return bytes(o)

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]; flags = [a for a in sys.argv[1:] if a.startswith('--')]
    HACK = '--hack' in flags                    # Hack-vN builder: sites kinds as an exception list, constants modulo 2^16
    L = lay.read_lay(args[0]); nl = lay.read_nl(args[1]); out = args[2]
    M16 = (lambda v: v & 0xFFFF) if HACK else (lambda v: v)
    ax, ay = L.parts['arm'][:2]
    R = lambda x, y: (x - ax, y - ay)
    sink_by_start = {}
    sinks = L.sinks
    # node pin sinks keyed by (site, pin); ports by name
    node_sink = {}; port_sink = {}; run_sinks = []
    for who, late, drv, pts in sinks:
        if who[0].startswith('n') and who[0][1:].isdigit():
            if late == 2: run_sinks.append((who, pts))
            else: node_sink[(int(who[0][1:]), int(who[1]))] = (drv, pts)
        else: port_sink[who[0]] = (drv, late, pts)
    lines = []; A = lines.append
    cols, rows, px, py = L.cols, L.rows, L.px, L.py
    gx0, gy0 = L.sites[0][0], L.sites[0][1]
    gx0r, gy0r = R(gx0, gy0)
    W = L.W
    A(f'// lay_data.asm -- GENERATED by tools/lay2asm.py from the layout tool output; do not edit.  Coordinates are relative to the arm.')
    A(f'.equ CHILD_DX, {W}')
    A(f'.equ COLS, {cols}'); A(f'.equ ROWS, {rows}'); A(f'.equ PX, {px}'); A(f'.equ PY, {py}'); A(f'.equ GX0, {M16(gx0r)}'); A(f'.equ GY0, {M16(gy0r)}')
    for nm in ('rom', 'arm', 'ram'):
        if nm in L.parts:
            x, y, rot, ab = L.parts[nm]; rx, ry = R(x, y)
            A(f'.equ {nm.upper()}_X, {M16(rx)}'); A(f'.equ {nm.upper()}_Y, {M16(ry)}'); A(f'.equ {nm.upper()}_ROT, {rot}'); A(f'.equ {nm.upper()}_AB, {ab}')
    ports = [n for n, _ in nl.ports]
    order = sorted(range(len(ports)), key=lambda i: (port_sink[ports[i]][1] if ports[i] in port_sink else 0, i))
    run_sinks.sort(key=lambda t: t[0])
    A(f'.equ NPORTS, {len(ports)}'); A(f'.equ NRUN, {len(run_sinks)}')
    kinds = []
    for (x, y, k, o) in L.sites: kinds.append(1 if k == 'D' else 2 if k == 'E' else 0)
    if HACK:
        A('lay_kinds:                                    // exception list: (n, kind) = n plain NAND sites, then one site of this kind (0 NAND filler, 1 DFF, 2 empty)')
        i = 0; ents = []; run = 0
        for k in kinds:
            if k == 0:
                run += 1
                if run == 255: ents.append((254, 0)); run = 0     # filler: 254 plain sites then one more plain site
                continue
            ents.append((run, k)); run = 0
        for _ in range(3): ents.append((254, 0))                    # read-ahead past the last exception
        pos = 0
        for (n, k) in ents:
            A(f'    .byte {n}, {k}                           // {n} NAND sites, then a ' + ('NAND (filler)', 'DFF', 'empty site')[k])
    else:
        A('lay_kinds:                                    // 2 bits per site, 4 sites per byte (first site in the low bits): 0 NAND, 1 DFF, 2 empty')
        while len(kinds) % 4: kinds.append(2)
        for i in range(0, len(kinds), 4):
            q = kinds[i:i + 4]; b = q[0] | q[1] << 2 | q[2] << 4 | q[3] << 6
            A(f'    .byte 0x{b:02X}                               // sites {i}..{i + 3}: ' + ' '.join('ND.'[v] for v in q))
    A('lay_paths:                                    // one path per sink; see tools/lay2asm.py for the segment byte')
    def emit(label, drv, pts):
        segs = segments(pts) if pts else []
        bs = enc_path(segs)
        txt = ' '.join(('L' if v == 0 and k == 0 else '') + '' for k, (v, d, n) in enumerate(segs))
        desc = ' '.join(f"{'v' if v else ''}{'RLDU'[d]}{n}" for (v, d, n) in segs) if segs else 'skip'
        A('    .byte ' + ', '.join(f'0x{b:02X}' for b in bs) + f'    // {label} <- {drv}: {desc}' + (' (starts on layer 1)' if segs and pts[0][2] == 1 else ''))
        return len(bs)
    total = 0
    for s, (x, y, k, o) in enumerate(L.sites):
        if k == 'E': continue
        for p in range(1 if k == 'D' else 2):
            drv, pts = node_sink.get((s, p), (None, None))
            if (s, p) in node_sink:
                assert pts[0][:2] == (x, y + p), ((s, p), pts[0], (x, y + p))
                total += emit(f'site {s} pin {"AB"[p]}', drv, pts)
            else: total += emit(f'site {s} pin {"AB"[p]}', 'open/RUN', None)
    A('lay_ports:')
    for i in order:
        n = ports[i]
        if n in port_sink:
            drv, late, pts = port_sink[n]; total += emit(f'port {n}', drv, pts)
        else: total += emit(f'port {n}', 'open', None)
    A('lay_run:')
    for who, pts in run_sinks: total += emit(f'RUN sink {who[0]} pin {who[1]}', 'tie', pts)
    A('lay_port_starts:                              // start cell (x, y) of each port, in stream order')
    for i in order:
        n = ports[i]; c = lay.port_cell(L, nl, n); rx, ry = R(*c); rx += W
        A(f'    .{"word" if HACK else "half"} {M16(rx)}, {M16(ry)}                          // {n}')
    A('lay_run_starts:')
    for who, pts in run_sinks:
        rx, ry = R(pts[0][0], pts[0][1]); rx += W; A(f'    .{"word" if HACK else "half"} {M16(rx)}, {M16(ry)}                          // RUN sink {who[0]} pin {who[1]}')
    A('lay_end:')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'path bytes {total}; sites {len(L.sites)}; ports {len(ports)}; run sinks {len(run_sinks)}; board {W}x{L.H}')

if __name__ == '__main__': main()
