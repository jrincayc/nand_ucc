"""hd.py -- data model, text reader and writer for the readable hardware description (HD) of the Y project.
(Copy of nandgen/y/tools/hd.py from the Project.)

HD text (see hd/core.hd):
  # comment
  param ab 14 / param ram_abits 5
  module NAME n_in n_out      (combinational, NAND-only; gates  gK = nand X Y   with X,Y in iK / gK;  out gK [gK])
  tile   NAME n_in n_out      (gates may also be  gK = dff X ; outputs as for a module)
  chain  NAME count           followed by one rule per tile input:  i3 = bcast REF | i11 = prev 0 | i0 = pick LIST shift | i2 = pick LIST mask
  body                        instance lines  NAME = TYPE REF REF ...    (TYPE: nand dff or a module name)
  ports                       PORT = REF      (rom_addr0.. arm_addr0.. arm_en wdata0..)
REF: an instance name, NAME.k for output k of a multi-output instance, romK, ramrdK, run, tie.
"""
import re


class HDError(Exception):
    pass


class Module:
    def __init__(self, name, n_in, n_out, kind='comb'):
        self.name, self.n_in, self.n_out, self.kind = name, n_in, n_out, kind
        self.gates = []            # comb: (a, b);  tile: ('nand', a, b) or ('dff', d)   (signal indices; inputs first)
        self.outs = []
        self.comments = []         # per gate, free text

    def n_gates(self): return len(self.gates)

    def gate_ins(self, g):
        x = self.gates[g]
        return x if self.kind == 'comb' else x[1:]

    def key(self): return (self.name, self.n_in, self.n_out, self.kind, tuple(self.gates), tuple(self.outs))


class Inst:
    def __init__(self, name, typ, refs, comment=''):
        self.name, self.type, self.refs, self.comment = name, typ, list(refs), comment


class HD:
    def __init__(self):
        self.params = {}
        self.modules = []          # library order = type numbers 2, 3, ... ; a tile module is also listed here
        self.chain = None          # dict(module=name, count=n, rules=[(input_idx, kind, args)])
        self.body = []
        self.ports = []            # (name, ref)

    def module(self, name):
        for m in self.modules:
            if m.name == name: return m
        raise HDError(f'no module {name}')

    def out_count(self, typ):
        if typ == 'nand' or typ == 'dff': return 1
        return self.module(typ).n_out

    def in_count(self, typ):
        if typ == 'nand': return 2
        if typ == 'dff': return 1
        return self.module(typ).n_in


def write(hd):
    L = ['# HD v1 -- readable hardware description (generated by hd_export.py; edit-by-hand is allowed)']
    for k, v in hd.params.items(): L.append(f'param {k} {v}')
    L.append('')
    for m in hd.modules:
        L.append(f'{"tile" if m.kind == "tile" else "module"} {m.name} {m.n_in} {m.n_out}')
        for g, x in enumerate(m.gates):
            cm = f'   # {m.comments[g]}' if g < len(m.comments) and m.comments[g] else ''
            sig = lambda s: f'i{s}' if s < m.n_in else f'g{s - m.n_in}'
            if x is None: L.append(f'  g{g} = hole{cm}')
            elif m.kind == 'comb': L.append(f'  g{g} = nand {sig(x[0])} {sig(x[1])}{cm}')
            elif x[0] == 'nand': L.append(f'  g{g} = nand {sig(x[1])} {sig(x[2])}{cm}')
            else: L.append(f'  g{g} = dff {sig(x[1])}{cm}')
        L.append('  out ' + ' '.join(f'g{o - m.n_in}' for o in m.outs))
        L.append('end')
        L.append('')
    if hd.chain:
        c = hd.chain
        L.append(f'chain {c["module"]} {c["count"]}')
        for k, v in c['lists'].items(): L.append(f'  list {k} = ' + ' '.join(v))
        for i, kind, args in c['rules']:
            L.append(f'  i{i} = {kind} ' + ' '.join(str(a) for a in args))
        L.append('end'); L.append('')
    L.append('body')
    for it in hd.body:
        L.append(f'  {it.name} = {it.type} ' + ' '.join(it.refs) + (f'   # {it.comment}' if it.comment else ''))
    L.append('end'); L.append('')
    L.append('ports')
    for n, r in hd.ports: L.append(f'  {n} = {r}')
    L.append('end')
    return '\n'.join(L) + '\n'


def read(text):
    hd = HD(); lines = [(n, l.split('#')[0].strip(), l) for n, l in enumerate(text.split('\n'), 1)]
    i = 0
    while i < len(lines):
        n, l, raw = lines[i]; i += 1
        if not l: continue
        w = l.split()
        if w[0] == 'param': hd.params[w[1]] = int(w[2]) if w[2].lstrip('-').isdigit() else w[2]
        elif w[0] in ('module', 'tile'):
            m = Module(w[1], int(w[2]), int(w[3]), 'tile' if w[0] == 'tile' else 'comb')
            while True:
                n, l, raw = lines[i]; i += 1
                if not l: continue
                if l == 'end': break
                t = l.split()
                if t[0] == 'out':
                    m.outs = [m.n_in + int(x[1:]) for x in t[1:]]; continue
                g = int(t[0][1:]); assert g == len(m.gates), f'line {n}: gates must be in order'
                def sg(x): return int(x[1:]) if x[0] == 'i' else m.n_in + int(x[1:])
                if t[2] == 'hole': m.gates.append(None)
                elif t[2] == 'nand': m.gates.append((sg(t[3]), sg(t[4])) if m.kind == 'comb' else ('nand', sg(t[3]), sg(t[4])))
                elif t[2] == 'dff' and m.kind == 'tile': m.gates.append(('dff', sg(t[3])))
                else: raise HDError(f'line {n}: bad gate {l}')
                m.comments.append(raw.split('#', 1)[1].strip() if '#' in raw else '')
            hd.modules.append(m)
        elif w[0] == 'chain':
            hd.chain = dict(module=w[1], count=int(w[2]), rules=[], lists={})
            while True:
                n, l, raw = lines[i]; i += 1
                if not l: continue
                if l == 'end': break
                t = l.split()
                if t[0] == 'list': hd.chain['lists'][t[1]] = t[3:]; continue
                idx = int(t[0][1:]); kind = t[2]
                hd.chain['rules'].append((idx, kind, [int(a) if a.lstrip('-').isdigit() else a for a in t[3:]]))
        elif w[0] == 'body':
            while True:
                n, l, raw = lines[i]; i += 1
                if not l: continue
                if l == 'end': break
                t = l.split(); assert t[1] == '=', f'line {n}'
                hd.body.append(Inst(t[0], t[2], t[3:], raw.split('#', 1)[1].strip() if '#' in raw else ''))
        elif w[0] == 'ports':
            while True:
                n, l, raw = lines[i]; i += 1
                if not l: continue
                if l == 'end': break
                t = l.split(); hd.ports.append((t[0], t[2]))
        else: raise HDError(f'line {n}: unknown section {l}')
    return hd
