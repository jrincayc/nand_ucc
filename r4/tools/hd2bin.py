#!/usr/bin/env python3
"""hd2bin.py HD OUT.s -- MECHANICAL encoder  module-level HD  ->  data assembly for the in-world kernels (kernels/hdflat.s, hdimp.s), plus an independent decoder.
No design decision is made here.  Layout (all little endian; labels emitted):
  hd_modoff  u16[NMODS+1]   byte offset of every module record from hd_mods (record extent = 4 + 3*slots + n_out of the SEED record; improved records keep the offset)
  hd_mods    records, Y format:  flags(1) n_in n_out n_slots,  entries (gate: 0x00 a b | skip: 0x02 count 0x00),  output signals (n_out bytes);  signal = n_in + slot
  hd_body    per instance: type byte (0 dff, 1 nand, 2+m module m) then one u16 reference per input
               reference: instance index | (output j << 12)   for a body instance (j = output of a multi-output instance)
                          0x4000 + j rom bit j          0x4008 + c RAM read bit c          0x4010 run
  hd_ports   per port 4 u16: part | side << 8 (0 rom, 1 arm, 2 ram; side 1 = right-hand pin), index a, reference, late (1 for arm_en)
  constants  HD_NMODS HD_NBODY HD_NPORTS HD_ROMB HD_RAMB
Instance numbers are positions in the body, so the node number of a flat gate is the running count of non-hole gates (hd2nl.py numbering)."""
import os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [HERE]
import hd as H


def record(m):
    ents = []; k = 0
    for x in m.gates:
        if x is None: k += 1; continue
        if k: ents.append((2, k, 0)); k = 0
        ents.append((0, x[0], x[1]))
    if k: ents.append((2, k, 0))
    b = [1, m.n_in, m.n_out, len(m.gates)]
    for e in ents: b += list(e)
    return b + list(m.outs)


def extent(m): return 4 + 3 * len(m.gates) + m.n_out


def port_geom(name, Q):
    if name.startswith('rom_addr'): return 0, 0, int(name[8:])
    if name.startswith('arm_addr'): return 1, 0, int(name[8:])
    if name == 'arm_en': return 1, 0, 4
    if name.startswith('wdata'): return 1, 1, int(name[5:])
    if name.startswith('ram_addr'): return 2, 0, int(name[8:])
    if name == 'ram_we': return 2, 0, Q
    if name.startswith('ram_din'): return 2, 0, Q + 1 + int(name[7:])
    raise KeyError(name)


def encode(hd):
    mods = [m for m in hd.modules]; assert all(m.kind == 'comb' for m in mods), 'tiles are not supported'
    tix = {m.name: 2 + i for i, m in enumerate(mods)}
    idx = {it.name: i for i, it in enumerate(hd.body)}
    def ref(r):
        if r == 'run': return 0x4010
        if r.startswith('rom') and r[3:].isdigit(): return 0x4000 + int(r[3:])
        if r.startswith('ramrd') and r[5:].isdigit(): return 0x4008 + int(r[5:])
        j = 0
        if '.' in r: r, j = r.split('.'); j = int(j)
        assert 0 <= j < 4 and idx[r] < 4096
        return idx[r] | (j << 12)
    out = {}
    out['mods'] = [record(m) for m in mods]; out['ext'] = [extent(m) for m in mods]
    out['body'] = [[0 if it.type == 'dff' else 1 if it.type == 'nand' else tix[it.type]] + [ref(r) for r in it.refs] for it in hd.body]
    Q = hd.params['ram_abits']
    out['ports'] = []
    for n, r in hd.ports:
        part, side, a = port_geom(n, Q); out['ports'].append([part | side << 8, a, ref(r), 1 if n == 'arm_en' else 0])
    out['romb'] = sum(1 for n, _ in hd.ports if n.startswith('rom_addr')); out['ramb'] = Q
    return out


def text(hd):
    e = encode(hd); L = ['// hd_data.s -- GENERATED by hd2bin.py from the HD file; do not edit by hand (see the header of hd2bin.py for the formats)']
    L += [f'.equ HD_NMODS, {len(e["mods"])}', f'.equ HD_NBODY, {len(e["body"])}', f'.equ HD_NPORTS, {len(e["ports"])}', f'.equ HD_ROMB, {e["romb"]}', f'.equ HD_RAMB, {e["ramb"]}']
    off = [0]
    for x in e['ext']: off.append(off[-1] + x)
    L.append('hd_modoff:'); L.append('    .half ' + ', '.join(str(x) for x in off))
    L.append('hd_mods:')
    for m, rec, x in zip(hd.modules, e['mods'], e['ext']):
        L.append(f'    .byte ' + ', '.join(str(b) for b in rec) + f'            // module {m.name}')
        pad = x - len(rec)
        if pad: L.append(f'    .space {pad}')
    L.append('hd_body:')
    for i, (it, rec) in enumerate(zip(hd.body, e['body'])):
        L.append(f'    .byte {rec[0]}')
        if len(rec) > 1: L.append('    .half ' + ', '.join(str(x) for x in rec[1:]) + f'            // {i}: {it.name} = {it.type} ' + ' '.join(it.refs))
    L.append('hd_ports:')
    for (n, r), rec in zip(hd.ports, e['ports']): L.append('    .half ' + ', '.join(str(x) for x in rec) + f'            // {n} = {r}')
    L.append('hd_end:')
    return '\n'.join(L) + '\n'


def decode(rom, sym, base):
    """independent decoder: ROM bytes + symbol table -> list of modules (name-less), body, ports (all as ints)"""
    at = lambda lab: sym[lab] - base
    u16 = lambda a: rom[a] | rom[a + 1] << 8
    NM, NB, NP = sym['HD_NMODS'], sym['HD_NBODY'], sym['HD_NPORTS']
    mods = []
    for m in range(NM):
        o = at('hd_mods') + u16(at('hd_modoff') + 2 * m); fl, ni, no, ns = rom[o:o + 4]; p = o + 4; slots = []
        while len(slots) < ns:
            k, a, b = rom[p:p + 3]; p += 3
            if k == 0: slots.append((a, b))
            else: slots += [None] * a
        mods.append((ni, no, slots, list(rom[p:p + no])))
    body = []; p = at('hd_body')
    for i in range(NB):
        t = rom[p]; p += 1; n = 1 if t == 0 else 2 if t == 1 else mods[t - 2][0]
        body.append((t, [u16(p + 2 * j) for j in range(n)])); p += 2 * n
    assert p == at('hd_ports')
    ports = [[u16(at('hd_ports') + 8 * i + 2 * j) for j in range(4)] for i in range(NP)]
    return mods, body, ports


if __name__ == '__main__':
    hd = H.read(open(sys.argv[1]).read()); open(sys.argv[2], 'w').write(text(hd))
