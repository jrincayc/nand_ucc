#!/usr/bin/env python3
"""iface_gen.py WIRES.pkl OUT.asm -- parametric interface emitter: bytecode (prog_if) + table t_idat. Constants derived from wires."""
import pickle, sys
W = pickle.load(open(sys.argv[1], 'rb')); O = (int(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) > 4 else (260, 40)
def pt(o): return (o[-2] + O[0], o[-1] + O[1])
A = W[:14]; B = W[14:22]; RA = W[22:38]; C = W[38:46]
def b16(v): v &= 0xffff; return [v & 255, v >> 8]
tab = []
for w in A: tab += b16(pt(w[-1])[0]) + b16(pt(w[-1])[1])
for w in RA: tab += b16(pt(w[-1])[0]) + b16(pt(w[-1])[1])
for w in B: tab += b16(w[0][1] + O[0]) + b16(w[0][2] + O[1])
for w in C:
    px, py = w[0][1] + O[0], w[0][2] + O[1]; ry = pt(w[1])[1]
    tab += b16(px) + b16(py) + b16(ry)
# constants
xa0 = A[0][0][1] + O[0]; xs = A[1][0][1] - A[0][0][1]
y0a = A[0][0][2] + O[1]; yra0 = pt(A[0][2])[1]; dyra = pt(A[1][2])[1] - yra0
xr0 = RA[0][0][1] + O[0]; y0r = RA[0][0][2] + O[1]; yrr0 = pt(RA[0][2])[1]; dyrr = pt(RA[1][2])[1] - yrr0
# B wire ops: p, s(0,q,oy), v, s(1,q,yr), v, s(0,x,yr), v, s(1,x,y0), v
q0 = pt(B[0][1])[0]; xb0 = pt(B[0][5])[0]; yrb0 = pt(B[0][3])[1]
# C wire ops: p, s1(px,ry), v, s0(rail,ry), v, s1(rail,yr), v, s0(x,yr), v, s1(x,y0), v
rail0 = pt(C[0][3])[0]; xc0 = pt(C[0][7])[0]; yrc0 = pt(C[0][5])[1]; y0c = pt(C[0][9])[1]
assert y0c == y0r
print(dict(xa0=xa0, xs=xs, y0a=y0a, yra0=yra0, dyra=dyra, xr0=xr0, y0r=y0r, yrr0=yrr0, dyrr=dyrr, q0=q0, xb0=xb0, yrb0=yrb0, rail0=rail0, xc0=xc0, yrc0=yrc0))
asm = f"""// generated by iface_gen.py
.equ IX,116
.equ IYR,118
.equ IQ,120
.equ IY0,122
.equ IDY,124
.equ IXS,126
iprog:
    SETW DP, t_idat
    SETW IX, {xa0 & 0xffff}
    SETW IYR, {yra0 & 0xffff}
    SETW IY0, {y0a & 0xffff}
    SETB IDY, {dyra & 255}
    SETB CNT2, 14
    CALLG i_a
    SETW IX, {xr0 & 0xffff}
    SETW IYR, {yrr0 & 0xffff}
    SETW IY0, {y0r & 0xffff}
    SETB IDY, {dyrr & 255}
    SETB CNT2, 16
    CALLG i_a
    SETW IQ, {q0 & 0xffff}
    SETW IX, {xb0 & 0xffff}
    SETW IYR, {yrb0 & 0xffff}
    SETW IY0, {y0a & 0xffff}
    SETB CNT2, 8
i_b:
    RDD CXV
    RDD CXV+1
    RDD LYV
    RDD LYV+1
    CPYW P0X, CXV
    CPYW P0Y, LYV
    CPYW P1X, IQ
    CPYW P1Y, LYV
    EMT 0
    CPYW P0X, IQ
    EMV
    CPYW P1Y, IYR
    EMT 1
    CPYW P0Y, IYR
    EMV
    CPYW P1X, IX
    EMT 0
    CPYW P0X, IX
    EMV
    CPYW P1Y, IY0
    EMT 1
    CPYW P0Y, IY0
    EMV
    ADDW IQ, 2
    ADDW IX, {xs}
    ADDW IYR, 65535
    DJNZ CNT2, i_b
    SETW IQ, {rail0 & 0xffff}
    SETW IX, {xc0 & 0xffff}
    SETW IYR, {yrc0 & 0xffff}
    SETW IY0, {y0c & 0xffff}
    SETB CNT2, 8
i_c:
    RDD CXV
    RDD CXV+1
    RDD LYV
    RDD LYV+1
    RDD OX
    RDD OX+1
    CPYW P0X, CXV
    CPYW P0Y, LYV
    CPYW P1X, CXV
    CPYW P1Y, OX
    EMT 1
    CPYW P0Y, OX
    EMV
    CPYW P1X, IQ
    EMT 0
    CPYW P0X, IQ
    EMV
    CPYW P1Y, IYR
    EMT 1
    CPYW P0Y, IYR
    EMV
    CPYW P1X, IX
    EMT 0
    CPYW P0X, IX
    EMV
    CPYW P1Y, IY0
    EMT 1
    CPYW P0Y, IY0
    EMV
    ADDW IQ, 2
    ADDW IX, {xs}
    ADDW IYR, 1
    DJNZ CNT2, i_c
    END
i_a:
    RDD CXV
    RDD CXV+1
    RDD LYV
    RDD LYV+1
    CPYW P0X, IX
    CPYW P0Y, IY0
    EMV
    CPYW P1X, IX
    CPYW P1Y, IYR
    EMT 1
    CPYW P0Y, IYR
    EMV
    CPYW P1X, CXV
    EMT 0
    CPYW P0X, CXV
    EMV
    CPYW P1Y, LYV
    EMT 1
    ADDW IX, {xs}
    ADDWV IYR, IDY
    DJNZ CNT2, i_a
    END
t_idat:
    .byte {','.join(map(str, tab))}
"""
open(sys.argv[2], 'w').write(asm); print('table bytes', len(tab))
