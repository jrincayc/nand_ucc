#!/usr/bin/env python3
"""hd2asm.py -- MECHANICAL encoder  HD (flat netlist)  ->  commented data assembly for rvasm.py, plus an independent decoder (image -> node graph).
No design decision is made here: every byte is a direct transcription of an HD line (quoted in the comment) or of the fixed port geometry.

Data layout (assembler labels; the data follows the builder code):
  hd_hot    64 x .half   hot table: absolute node numbers of the most referenced nodes
  hd_ports  NPORTS records: ref, then px+32, py+32, r+32 (sink pad and lane row relative to the child arm; for a RAM port px has bit 7 set and
            the three values are relative to the RAM origin)
  hd_body   NCORE node records, then hd_end.  Record: [0x00 if the node is a DFF] then 1 (DFF) or 2 (NAND) references.
Reference byte(s), relative to the current node (the node being described; for ports the tie node, number NCORE):
  0x01..0x7F  node `cur - b`           0x80..0x87  ROM data bit j        0x88  tie-high node        0x89  RUN
  0x8A..0x91  RAM read bit c           0xA0..0xBF  absolute node number ((b & 31) << 8) | next byte
  0xC0..0xFF  hot table entry b - 0xC0
Assembler constants emitted: NCORE, NPORTS, NHOT."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE]
import hd as H, ref_flatten as RF


class Enc:
    def __init__(self, hd):
        self.hd = hd; self.f = RF.flatten(hd); f = self.f
        assert f.W == 0 and f.ram_part, 'flat machine with a RAM part expected'
        fan = {}
        for g in range(f.n_core):
            for s in f.ins[g]:
                if s[0] == 'n' and s[1] != f.tie: fan[s[1]] = fan.get(s[1], 0) + 1
        for n, s in f.ports:
            if s[0] == 'n' and s[1] != f.tie: fan[s[1]] = fan.get(s[1], 0) + 1
        # a node is worth a hot slot by the bytes it saves: each far reference costs 2 bytes, a hot one costs 1
        def far(g, s): return not (1 <= g - s <= 127)
        gain = {}
        for g in range(f.n_core):
            for s in f.ins[g]:
                if s[0] == 'n' and s[1] != f.tie and far(g, s[1]): gain[s[1]] = gain.get(s[1], 0) + 1
        for n, s in f.ports:
            if s[0] == 'n' and s[1] != f.tie and far(f.n_core, s[1]): gain[s[1]] = gain.get(s[1], 0) + 1
        self.hot = [n for n, _ in sorted(gain.items(), key=lambda kv: (-kv[1], kv[0]))[:64]]
        self.hot_gain = gain
        self.hotidx = {n: i for i, n in enumerate(self.hot)}
        self.lines = []

    def emit(self, text, comment): self.lines.append((text, comment))
    def byt(self, bs, comment): self.emit('.byte ' + ', '.join('0x%02X' % b for b in bs), comment)

    def ref(self, name, cur):
        """-> list of bytes for the reference `name` (an HD ref string) from node `cur`"""
        f = self.f
        if name == 'run': return [0x89]
        if name == 'tie': return [0x88]
        if name.startswith('rom') and name[3:].isdigit(): return [0x80 + int(name[3:])]
        if name.startswith('ramrd') and name[5:].isdigit(): return [0x8A + int(name[5:])]
        kind, t = f.resolve(name)
        assert kind == 'n'
        if t == f.tie: return [0x88]
        d = cur - t
        if 1 <= d <= 127: return [d]
        if t in self.hotidx: return [0xC0 + self.hotidx[t]]
        assert t < 8192
        return [0xA0 | (t >> 8), t & 255]

    def encode(self):
        hd, f = self.hd, self.f
        E = self.emit
        E('', 'hd_data.asm -- GENERATED by hd2asm.py from the HD file; do not edit by hand (edit the generator or the .hd and regenerate)')
        E('', 'layout and byte formats: see the header of hd2asm.py')
        E(f'.equ NCORE, {f.n_core}', 'number of core nodes (the tie-high node is node NCORE)')
        E(f'.equ NPORTS, {len(hd.ports)}', 'number of port records')
        E(f'.equ NHOT, {len(self.hot)}', 'hot table entries')
        E('hd_hot:', 'label: hot table (absolute node numbers)')
        for i, n in enumerate(self.hot):
            E(f'.half {n}', f'hot {i} = node {n} ({self.hot_gain[n]} far references)')
        E('hd_ports:', 'label: ports (ref, sink pad x, y, lane row)')
        want = [n for n, _ in hd.ports]
        for n, r in hd.ports:
            px, py, rr = RF.port_sink(n, f)
            if n.startswith('ram_'):
                self.byt(self.ref(r, f.n_core) + [0x80 | (px - f.RX + 32), py - f.RY + 32, rr - f.RY + 32],
                         f'port {n} = {r}; sink pad (RAM origin + {px - f.RX},{py - f.RY}), lane row = pad row')
            else:
                self.byt(self.ref(r, f.n_core) + [px + 32, py + 32, rr + 32], f'port {n} = {r}; sink pad ({px},{py}), lane row {rr} (relative to the child arm; each stored +32)')
        E('hd_body:', 'label: body (one record per core node)')
        for g, inst in enumerate(hd.body):
            bs = [0] if inst.type == 'dff' else []
            for r in inst.refs: bs += self.ref(r, g)
            cm = f'{inst.name} = {inst.type} ' + ' '.join(inst.refs) + (f'   # {inst.comment}' if inst.comment else '')
            self.byt(bs, f'node {g}: ' + cm)
        E('hd_end:', 'label: end of the image (the ROM copy stops here)')
        nrun = sum(1 for g in range(f.n_core) for s in f.ins[g] if s[0] == 'run')
        assert nrun <= 2, f'{nrun} RUN sinks; the builder reserves 2 slots'
        return self

    def text(self):
        out = []
        for t, c in self.lines:
            if not t: out.append('// ' + c)
            elif t.endswith(':') and not t.startswith('.'): out.append(f'{t:<12}// {c}')
            else: out.append(f'    {t:<44}// {c}')
        return '\n'.join(out) + '\n'


# ------------------------------------------------------------------------------------------------ decoder (independent of the encoder)
class Dec:
    pass


def decode(image, ncore, nports, nhot, hot_off, ports_off, body_off):
    """image: bytes from ROM_BASE; offsets of the three sections inside it.  -> object with kind, ins (as ref_flatten.Flat) and ports"""
    rd = lambda a: image[a]
    hot = [rd(hot_off + 2 * i) | rd(hot_off + 2 * i + 1) << 8 for i in range(nhot)]
    def dref(p, cur):
        b = rd(p)
        if 1 <= b <= 0x7F: return ('n', cur - b), p + 1
        if 0x80 <= b <= 0x87: return ('rom', b - 0x80), p + 1
        if b == 0x88: return ('tie',), p + 1
        if b == 0x89: return ('run',), p + 1
        if 0x8A <= b <= 0x91: return ('ramrd', b - 0x8A), p + 1
        if 0xA0 <= b <= 0xBF: return ('n', (b & 31) << 8 | rd(p + 1)), p + 2
        if b >= 0xC0: return ('n', hot[b - 0xC0]), p + 1
        raise ValueError(f'bad ref byte {b:#x} at {p:#x}')
    f = Dec(); f.kind, f.ins = [], []
    pos = body_off
    for g in range(ncore):
        isdff = rd(pos) == 0
        if isdff: pos += 1
        src = []
        for _ in range(1 if isdff else 2):
            s, pos = dref(pos, g); src.append(s)
        f.kind.append('dff' if isdff else 'nand'); f.ins.append(src)
    f.end = pos
    pos = ports_off; f.ports = []
    for _ in range(nports):
        s, pos = dref(pos, ncore); f.ports.append((s, rd(pos), rd(pos + 1), rd(pos + 2))); pos += 3
    f.n_core = ncore
    return f


if __name__ == '__main__':
    hd = H.read(open(sys.argv[1]).read()); e = Enc(hd).encode()
    open(sys.argv[2], 'w').write(e.text())
    print(f'{len(e.lines)} lines')
