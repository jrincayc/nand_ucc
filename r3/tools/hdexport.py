#!/usr/bin/env python3
"""hdexport.py -- write the generated CPU netlist as an HD file (flat body: nand / dff instances).
usage: hdexport.py OUT.hd"""
import os, sys
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__))]
import cpu_gen
from netlist import Net

PORT_ORDER = ([f'rom_addr{i}' for i in range(14)] + [f'arm_addr{i}' for i in range(4)] + [f'wdata{i}' for i in range(8)] +
              [f'ram_addr{i}' for i in range(8)] + ['ram_we'] + [f'ram_din{i}' for i in range(8)] + ['arm_en'])


def flat(x):
    for y in x:
        if isinstance(y, list): yield from flat(y)
        else: yield y


def order_nodes(net, roots):
    """DFFs first (their D references are forward), then the logic in depth-first post-order from the DFF D inputs and the ports, so that
    most references are short backward distances."""
    used = net.used_nodes(roots)
    dffs = sorted(n for n in used if net.kind[n][0] == 'dff')
    order = list(dffs); seen = set(dffs)
    starts = [net.kind[n][1] for n in dffs] + [r for r in roots if net.kind[r][0] == 'nand']
    for r in starts:
        if r in seen or net.kind[r][0] != 'nand': continue
        stack = [(r, 0)]
        while stack:
            x, st = stack.pop()
            if st == 0:
                if x in seen: continue
                seen.add(x); stack.append((x, 1))
                for s_ in reversed(net.kind[x][1:]):
                    if net.kind[s_][0] == 'nand' and s_ not in seen: stack.append((s_, 0))
            else: order.append(x)
    assert len(order) == len([n for n in used if net.kind[n][0] != 'in']), (len(order), len(used))
    return order


def export(net, ports, state, path, comment=''):
    roots = [ports[p] for p in PORT_ORDER] + list(flat(v if isinstance(v, list) else [v] for v in state.values()))
    nodes = order_nodes(net, roots)
    name = {}
    for i, n in enumerate(nodes): name[n] = f'n{i}'
    def ref(s):
        if net.kind[s][0] == 'in': return s_in[s]
        return name[s]
    s_in = {}
    for nm, n in net.inputs.items(): s_in[n] = nm
    L = ['# HD v1 -- flat netlist generated by hdexport.py (cpu_gen.py); do not edit by hand', 'param ab 15', 'param ram_abits 8', 'param ram_part 1', '', 'body']
    for n in nodes:
        k = net.kind[n]
        dbg = net.names.get(n, '')
        if k[0] == 'nand': L.append(f'  {name[n]} = nand {ref(k[1])} {ref(k[2])}' + (f'   # {dbg}' if dbg else ''))
        else: L.append(f'  {name[n]} = dff {ref(k[1])}' + (f'   # {dbg}' if dbg else ''))
    L += ['end', '', 'ports']
    for p in PORT_ORDER: L.append(f'  {p} = {name[ports[p]]}')
    L.append('end')
    open(path, 'w').write('\n'.join(L) + '\n')
    return len(nodes)


if __name__ == '__main__':
    net, ports, state = cpu_gen.build()
    n = export(net, ports, state, sys.argv[1])
    print(n, 'nodes written to', sys.argv[1])
